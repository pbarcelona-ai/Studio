    def handle_prompt(self, body: dict[str, Any]) -> tuple[int, dict[str, Any]]:
        with self._lock:
            if self._validation_error is not None:
                return HTTPStatus.BAD_REQUEST, dict(self._validation_error)
            self._seq += 1
            seq = self._seq
            pid = str(uuid.uuid4())
            workflow = body.get("prompt") if isinstance(body.get("prompt"), dict) else {}
            client_id = str(body.get("client_id") or "")
            self.prompts.append({"prompt_id": pid, "number": seq, "client_id": client_id, "prompt": workflow})
            self.loaded_models.add("active_workflow")
            self._running_prompts[pid] = [seq, pid, workflow, {"client_id": client_id}, []]
            exec_err = self._execution_error
            steps = max(1, int(self.steps))
            delay = max(0.0, float(self.step_delay_s))
            preview_fmt = self.preview_format
            out_fmt = self.output_format

            worker = threading.Thread(
                target=self._execute_prompt,
                args=(pid, seq, workflow, client_id, steps, delay, preview_fmt, out_fmt, exec_err),
                daemon=True,
            )
            self._workers = [w for w in self._workers if w.is_alive()]
            self._workers.append(worker)
            worker.start()
        return HTTPStatus.OK, {"prompt_id": pid, "number": seq, "node_errors": {}}

    @staticmethod
    def _select_nodes(workflow: dict[str, Any]) -> tuple[str, str]:
        node_ids = [str(k) for k in workflow] if workflow else ["3", "9"]
        sampler_node = node_ids[0]
        for nid in node_ids:
            node_def = workflow.get(nid)
            if not isinstance(node_def, dict):
                continue
            ctype = str(node_def.get("class_type") or "")
            if ctype.startswith(("KSampler", "SamplerCustom")):
                sampler_node = nid
                break

        primary_output_types = {"SaveImage", "SaveVideo", "VHS_VideoCombine"}
        output_node: str | None = None
        for nid in reversed(node_ids):
            node_def = workflow.get(nid)
            if not isinstance(node_def, dict):
                continue
            ctype = str(node_def.get("class_type") or "")
            if ctype in primary_output_types or ctype.startswith("SaveAudio"):
                output_node = nid
                break
        if output_node is None:
            for nid in reversed(node_ids):
                node_def = workflow.get(nid)
                if isinstance(node_def, dict) and str(node_def.get("class_type") or "") == "PreviewImage":
                    output_node = nid
                    break
        return sampler_node, output_node if output_node is not None else node_ids[-1]

    def _execute_prompt(
        self,
        pid: str,
        seq: int,
        workflow: dict[str, Any],
        client_id: str,
        steps: int,
        delay: float,
        preview_fmt: int,
        out_fmt: str,
        exec_err: str | None,
    ) -> None:
        try:
            ts0 = int(time.time() * 1000)
            sampler_node, output_node = self._select_nodes(workflow)

            for target in self._ws_targets(client_id):
                target.send_text({"type": "status", "data": {"status": {"exec_info": {"queue_remaining": 1}}}})
                target.send_text({"type": "execution_start", "data": {"prompt_id": pid, "timestamp": ts0}})

            preview_bytes = MINIMAL_PNG if preview_fmt == 2 else MINIMAL_JPEG
            binary_frame = struct.pack(">II", 1, preview_fmt) + preview_bytes

            for step in range(1, steps + 1):
                if delay > 0 and self._stop_event.wait(delay):
                    return
                if self._stop_event.is_set():
                    return
                for target in self._ws_targets(client_id):
                    target.send_text({
                        "type": "executing",
                        "data": {"node": sampler_node, "display_node": sampler_node, "prompt_id": pid},
                    })
                    target.send_text({
                        "type": "progress",
                        "data": {"value": step, "max": steps, "prompt_id": pid, "node": sampler_node},
                    })
                    target.send_binary(binary_frame)

            ts1 = int(time.time() * 1000)
            if exec_err is not None:
                err_data = {
                    "prompt_id": pid,
                    "node_id": sampler_node,
                    "node_type": "KSampler",
                    "exception_message": exec_err,
                    "exception_type": "RuntimeError",
                    "traceback": [exec_err],
                }
                with self._lock:
                    self.history[pid] = {
                        "prompt": [seq, pid, workflow, {"client_id": client_id}, [output_node]],
                        "outputs": {},
                        "status": {
                            "status_str": "error",
                            "completed": True,
                            "messages": [
                                ["execution_start", {"prompt_id": pid, "timestamp": ts0}],
                                ["execution_error", err_data],
                            ],
                        },
                    }
                for target in self._ws_targets(client_id):
                    target.send_text({"type": "execution_error", "data": err_data})
                    target.send_text({"type": "status", "data": {"status": {"exec_info": {"queue_remaining": 0}}}})
                return

            ext = out_fmt.lower().lstrip(".")
            if ext == "jpeg":
                out_bytes, ctype, out_key = MINIMAL_JPEG, "image/jpeg", "images"
            elif ext == "wav":
                out_bytes, ctype, out_key = b"RIFF\x24\x00\x00\x00WAVEfmt ", "audio/wav", "audio"
            elif ext == "mp4":
                out_bytes, ctype, out_key = b"\x00\x00\x00\x18ftypmp42", "video/mp4", "gifs"
            else:
                ext = "png"
                out_bytes, ctype, out_key = MINIMAL_PNG, "image/png", "images"

            out_filename = f"ComfyUI_{seq:05d}_.{ext}"
            artifact_meta = {"filename": out_filename, "subfolder": "", "type": "output"}
            outputs_payload = {output_node: {out_key: [artifact_meta]}}

            with self._lock:
                self._artifacts[("output", "", out_filename)] = (out_bytes, ctype)
                self.history[pid] = {
                    "prompt": [seq, pid, workflow, {"client_id": client_id}, [output_node]],
                    "outputs": outputs_payload,
                    "status": {
                        "status_str": "success",
                        "completed": True,
                        "messages": [
                            ["execution_start", {"prompt_id": pid, "timestamp": ts0}],
                            ["execution_success", {"prompt_id": pid, "timestamp": ts1}],
                        ],
                    },
                }

            for target in self._ws_targets(client_id):
                target.send_text({
                    "type": "executed",
                    "data": {
                        "node": output_node,
                        "display_node": output_node,
                        "output": {out_key: [artifact_meta]},
                        "prompt_id": pid,
                    },
                })
                target.send_text({"type": "executing", "data": {"node": None, "prompt_id": pid}})
                target.send_text({"type": "status", "data": {"status": {"exec_info": {"queue_remaining": 0}}}})
        finally:
            cur = threading.current_thread()
            with self._lock:
                self._running_prompts.pop(pid, None)
                self._workers = [w for w in self._workers if w is not cur]
