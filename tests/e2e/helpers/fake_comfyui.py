    def register_ws(self, conn: _WSServerConn, thread: threading.Thread | None = None) -> None:
        with self._lock:
            self._ws_clients.append(conn)
            if thread is not None and thread not in self._ws_threads:
                self._ws_threads.append(thread)

    def unregister_ws(self, conn: _WSServerConn, thread: threading.Thread | None = None) -> None:
        with self._lock:
            self._ws_clients = [c for c in self._ws_clients if c is not conn]
            if thread is not None:
                self._ws_threads = [t for t in self._ws_threads if t is not thread]

