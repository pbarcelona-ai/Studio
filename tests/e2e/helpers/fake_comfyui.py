    def view_artifact(
        self,
        filename: str,
        *,
        subfolder: str = "",
        folder_type: str = "output",
    ) -> tuple[int, str, bytes]:
        if (
            not filename
            or "/" in filename
            or "\\" in filename
            or ".." in filename
            or ".." in subfolder
            or subfolder.startswith("/")
        ):
            return HTTPStatus.BAD_REQUEST, "text/plain", b"invalid filename"
        with self._lock:
            item = self._artifacts.get((folder_type, subfolder, filename))
        if item is None:
            return HTTPStatus.NOT_FOUND, "text/plain", b"not found"
        data, ctype = item
        return HTTPStatus.OK, ctype, data

    def handle_upload(self, content_type: str, raw_body: bytes) -> tuple[int, dict[str, Any]]:
        header_block = f"Content-Type: {content_type}\r\nMIME-Version: 1.0\r\n\r\n".encode("latin-1")
        msg = BytesParser(policy=email_default_policy).parsebytes(header_block + raw_body)
        filename = "upload.png"
        payload = raw_body
        subfolder = ""
        if msg.is_multipart():
            for part in msg.iter_parts():
                name = part.get_param("name", header="content-disposition")
                if name == "image":
                    filename = Path(part.get_filename() or "upload.png").name
                    part_bytes = part.get_payload(decode=True)
                    if isinstance(part_bytes, bytes):
                        payload = part_bytes
                elif name == "subfolder":
                    val = part.get_payload(decode=True)
                    if isinstance(val, bytes):
                        subfolder = val.decode("utf-8", errors="replace").strip("/")
        with self._lock:
            self.uploads[filename] = payload
            self._artifacts[("input", subfolder, filename)] = (payload, _guess_content_type(filename))
        return HTTPStatus.OK, {"name": filename, "subfolder": subfolder, "type": "input"}

