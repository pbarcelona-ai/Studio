    def start(self) -> FakeComfyUIServer:
        if self._thread is None:
            self._stop_event.clear()
            self._thread = threading.Thread(target=self._httpd.serve_forever, daemon=True)
            self._thread.start()
        return self

    def close(self) -> None:
        self._stop_event.set()
        with self._lock:
            clients = list(self._ws_clients)
            workers = list(self._workers)
            ws_threads = list(self._ws_threads)
        for c in clients:
            c.close()
        if self._thread is not None:
            self._httpd.shutdown()
            self._thread.join(timeout=2.0)
            self._thread = None
        self._httpd.server_close()
        cur = threading.current_thread()
        for w in workers:
            if w is not cur:
                w.join(timeout=2.0)
        for wt in ws_threads:
            if wt is not cur:
                wt.join(timeout=2.0)

    def __enter__(self) -> FakeComfyUIServer:
        return self.start()

    def __exit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        self.close()

    def reset(self) -> None:
        self._stop_event.set()
        with self._lock:
            workers = list(self._workers)
        cur = threading.current_thread()
        for w in workers:
            if w is not cur:
                w.join(timeout=2.0)
        with self._lock:
            if self._thread is not None:
                self._stop_event.clear()
            self._seq = 0
            self._validation_error = None
            self._execution_error = None
            self._errors.clear()
            self._workers = [w for w in self._workers if w.is_alive()]
            self._running_prompts.clear()
            self.prompts.clear()
            self.free_calls.clear()
            self.queue_calls.clear()
            self.interrupt_calls.clear()
            self.uploads.clear()
            self.loaded_models = {"flux1-dev.safetensors"}
            self.history.clear()
            self._artifacts.clear()

    def set_error(self, endpoint: str, status: int | None, body: Any = None) -> None:
        key = endpoint if endpoint.startswith("/") else f"/{endpoint}"
        with self._lock:
            if status is None:
                self._errors.pop(key, None)
                return
            if body is None:
                payload = json.dumps({"error": f"injected error {status} on {key}"}).encode("utf-8")
                ctype = "application/json"
            elif isinstance(body, bytes):
                payload = body
                ctype = "application/json"
            elif isinstance(body, str):
                payload = body.encode("utf-8")
                ctype = "text/plain; charset=utf-8"
            else:
                payload = json.dumps(body).encode("utf-8")
                ctype = "application/json"
            self._errors[key] = (int(status), ctype, payload)

    def clear_errors(self) -> None:
        with self._lock:
            self._errors.clear()

    def get_error(self, path: str) -> tuple[int, str, bytes] | None:
        with self._lock:
            if path in self._errors:
                return self._errors[path]
            for ep, err in self._errors.items():
                ep_clean = ep.rstrip("/")
                if ep_clean and path.startswith(ep_clean + "/"):
                    return err
            return None

