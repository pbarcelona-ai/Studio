def _guess_content_type(filename: str) -> str:
    ext = Path(filename).suffix.lower()
    if ext == ".png":
        return "image/png"
    if ext in {".jpg", ".jpeg"}:
        return "image/jpeg"
    if ext == ".wav":
        return "audio/wav"
    if ext == ".mp4":
        return "video/mp4"
    if ext == ".webp":
        return "image/webp"
    return "application/octet-stream"


def _ws_accept_key(sec_key: str) -> str:
    digest = hashlib.sha1((sec_key.strip() + _WS_GUID).encode("ascii")).digest()
    return base64.b64encode(digest).decode("ascii")


def _encode_ws_frame(opcode: int, payload: bytes, *, mask: bool = False) -> bytes:
    first = 0x80 | (opcode & 0x0F)
    length = len(payload)
    mask_bit = 0x80 if mask else 0x00
    header = bytearray([first])
    if length < 126:
        header.append(mask_bit | length)
    elif length <= 0xFFFF:
        header.append(mask_bit | 126)
        header.extend(struct.pack("!H", length))
    else:
        header.append(mask_bit | 127)
        header.extend(struct.pack("!Q", length))

    if mask:
        mask_key = os.urandom(4)
        header.extend(mask_key)
        masked = bytes(b ^ mask_key[idx % 4] for idx, b in enumerate(payload))
        return bytes(header) + masked
    return bytes(header) + payload


def _recv_exact(sock: socket.socket, n: int) -> bytes:
    buf = bytearray()
    while len(buf) < n:
        chunk = sock.recv(n - len(buf))
        if not chunk:
            raise EOFError("unexpected EOF on WebSocket")
        buf.extend(chunk)
    return bytes(buf)


def _read_ws_frame(sock: socket.socket) -> tuple[int, bytes]:
    b1, b2 = _recv_exact(sock, 2)
    opcode = b1 & 0x0F
    masked = bool(b2 & 0x80)
    length = b2 & 0x7F
    if length == 126:
        (length,) = struct.unpack("!H", _recv_exact(sock, 2))
    elif length == 127:
        (length,) = struct.unpack("!Q", _recv_exact(sock, 8))
    mask_key = _recv_exact(sock, 4) if masked else b""
    payload = _recv_exact(sock, length) if length else b""
    if masked:
        payload = bytes(b ^ mask_key[idx % 4] for idx, b in enumerate(payload))
    return opcode, payload


@dataclass
class WSFrame:
    """Decoded WebSocket frame returned by WSClient."""

    opcode: int
    payload: bytes

    @property
    def is_text(self) -> bool:
        return self.opcode == 0x1

    @property
    def is_binary(self) -> bool:
        return self.opcode == 0x2

    @property
    def is_pong(self) -> bool:
        return self.opcode == 0xA

    @property
    def is_close(self) -> bool:
        return self.opcode == 0x8

    def text(self) -> str:
        return self.payload.decode("utf-8")

    def json(self) -> dict[str, Any]:
        parsed = json.loads(self.text())
        return parsed if isinstance(parsed, dict) else {"value": parsed}

    def parse_preview_image(self) -> tuple[int, int, bytes]:
        """Parse ComfyUI PREVIEW_IMAGE binary frame: (event_type, image_format, image_bytes)."""
        if len(self.payload) < 8:
            raise ValueError("binary frame too short for ComfyUI PREVIEW_IMAGE header")
        event_type, img_format = struct.unpack(">II", self.payload[:8])
        return event_type, img_format, self.payload[8:]


class WSClient:
    """Lightweight stdlib RFC 6455 WebSocket client for testing FakeComfyUIServer."""

    def __init__(self, sock: socket.socket, initial_bytes: bytes = b"") -> None:
        self._sock = sock
        self._rx_buf = bytearray(initial_bytes)
        self._closed = False

    def _recv_exact(self, n: int) -> bytes:
        while len(self._rx_buf) < n:
            chunk = self._sock.recv(max(4096, n - len(self._rx_buf)))
            if not chunk:
                raise EOFError("unexpected EOF on WebSocket")
            self._rx_buf.extend(chunk)
        out = bytes(self._rx_buf[:n])
        del self._rx_buf[:n]
        return out

    def _read_frame(self) -> tuple[int, bytes]:
        b1, b2 = self._recv_exact(2)
        opcode = b1 & 0x0F
        masked = bool(b2 & 0x80)
        length = b2 & 0x7F
        if length == 126:
            (length,) = struct.unpack("!H", self._recv_exact(2))
        elif length == 127:
            (length,) = struct.unpack("!Q", self._recv_exact(8))
        mask_key = self._recv_exact(4) if masked else b""
        payload = self._recv_exact(length) if length else b""
        if masked:
            payload = bytes(b ^ mask_key[idx % 4] for idx, b in enumerate(payload))
        return opcode, payload

    def recv_frame(self, timeout: float | None = None) -> WSFrame:
        if timeout is not None:
            self._sock.settimeout(timeout)
        while True:
            opcode, payload = self._read_frame()
            if opcode == 0x9:  # Ping -> automatic Pong
                self._sock.sendall(_encode_ws_frame(0xA, payload, mask=True))
                continue
            if opcode == 0x8:  # Close
                if not self._closed:
                    self._closed = True
                    try:
                        self._sock.sendall(_encode_ws_frame(0x8, b"", mask=True))
                    except OSError:
                        pass
                return WSFrame(opcode=opcode, payload=payload)
            return WSFrame(opcode=opcode, payload=payload)

    def recv_json(self, timeout: float | None = None) -> dict[str, Any]:
        while True:
            frame = self.recv_frame(timeout=timeout)
            if frame.is_text:
                return frame.json()
            if frame.is_close:
                raise EOFError("WebSocket closed before receiving text frame")

    def send_text(self, text: str) -> None:
        self._sock.sendall(_encode_ws_frame(0x1, text.encode("utf-8"), mask=True))

    def send_ping(self, data: bytes = b"ping") -> None:
        self._sock.sendall(_encode_ws_frame(0x9, data, mask=True))

    def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        try:
            self._sock.sendall(_encode_ws_frame(0x8, b"", mask=True))
        except OSError:
            pass
        try:
            self._sock.close()
        except OSError:
            pass

    def __enter__(self) -> WSClient:
        return self

    def __exit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        self.close()


def connect_ws(base_url: str, client_id: str | None = None, *, timeout: float = 5.0) -> WSClient:
    """Connect to a WebSocket endpoint on FakeComfyUIServer using stdlib socket."""
    parsed = urlparse(base_url)
    host = parsed.hostname or "127.0.0.1"
    port = parsed.port or 8188
    cid = client_id or f"test-{uuid.uuid4().hex[:8]}"
    path = f"/ws?clientId={cid}"

    sock = socket.create_connection((host, port), timeout=timeout)
    key = base64.b64encode(os.urandom(16)).decode("ascii")
    req = (
        f"GET {path} HTTP/1.1\r\n"
        f"Host: {host}:{port}\r\n"
        "Upgrade: websocket\r\n"
        "Connection: Upgrade\r\n"
        f"Sec-WebSocket-Key: {key}\r\n"
        "Sec-WebSocket-Version: 13\r\n"
        "\r\n"
    ).encode("ascii")
    sock.sendall(req)

    buf = bytearray()
    while b"\r\n\r\n" not in buf:
        chunk = sock.recv(4096)
        if not chunk:
            sock.close()
            raise ConnectionError("EOF during WebSocket handshake")
        buf.extend(chunk)
    raw_buf = bytes(buf)
    header_bytes, leftover = raw_buf.split(b"\r\n\r\n", 1)
    raw_headers = header_bytes.decode("latin-1")
    lines = raw_headers.split("\r\n")
    if "101" not in lines[0]:
        sock.close()
        raise ConnectionError(f"WebSocket handshake failed: {lines[0]}")
    hdr_map: dict[str, str] = {}
    for line in lines[1:]:
        if ":" in line:
            k, v = line.split(":", 1)
            hdr_map[k.strip().lower()] = v.strip()
    expected_accept = _ws_accept_key(key)
    if hdr_map.get("sec-websocket-accept") != expected_accept:
        sock.close()
        raise ConnectionError("Invalid Sec-WebSocket-Accept header")
    return WSClient(sock, initial_bytes=leftover)


class _WSServerConn:
    def __init__(self, client_id: str, sock: socket.socket) -> None:
        self.client_id = client_id
        self.sock = sock
        self._send_lock = threading.Lock()
        self.closed = False

    def send_text(self, obj: dict[str, Any]) -> bool:
        return self._send_raw(0x1, json.dumps(obj).encode("utf-8"))

    def send_binary(self, data: bytes) -> bool:
        return self._send_raw(0x2, data)

    def send_pong(self, data: bytes) -> bool:
        return self._send_raw(0xA, data)

    def close(self) -> None:
        with self._send_lock:
            if self.closed:
                return
            self.closed = True
            try:
                self.sock.sendall(_encode_ws_frame(0x8, b"", mask=False))
            except OSError:
                pass
            try:
                self.sock.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass

    def _send_raw(self, opcode: int, payload: bytes) -> bool:
        frame = _encode_ws_frame(opcode, payload, mask=False)
        with self._send_lock:
            if self.closed:
                return False
            try:
                self.sock.sendall(frame)
                return True
            except OSError:
                self.closed = True
                return False


class _ComfyHTTPServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True
    request_queue_size = 128

    def __init__(self, server_address: tuple[str, int], fake: FakeComfyUIServer) -> None:
        self.fake = fake
        super().__init__(server_address, _ComfyHandler)


class _ComfyHandler(BaseHTTPRequestHandler):
    server: _ComfyHTTPServer
    protocol_version = "HTTP/1.1"
    rbufsize = 0

    def log_message(self, format: str, *args: Any) -> None:
        return

    def _send_bytes(self, status: int, content_type: str, payload: bytes) -> None:
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("Connection", "close")
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(payload)

    def _send_json(self, status: int, obj: Any) -> None:
        self._send_bytes(status, "application/json", json.dumps(obj).encode("utf-8"))

    def _read_body(self) -> bytes:
        length = int(self.headers.get("Content-Length") or "0")
        if length < 0:
            raise ValueError(f"negative Content-Length: {length}")
        return self.rfile.read(length) if length > 0 else b""

    def _read_json(self) -> dict[str, Any]:
        raw = self._read_body()
        if not raw.strip():
            return {}
        parsed = json.loads(raw.decode("utf-8"))
        return parsed if isinstance(parsed, dict) else {}

    def _maybe_send_injected_error(self, path: str) -> bool:
        err = self.server.fake.get_error(path)
        if err is None:
            return False
        status, ctype, payload = err
        self._send_bytes(status, ctype, payload)
        return True

    def do_GET(self) -> None:
        parsed = urlparse(self.path)
        path = parsed.path
        query = parse_qs(parsed.query)
        fake = self.server.fake

        if path == "/ws" and self.headers.get("Upgrade", "").lower() == "websocket":
            self._handle_websocket(query)
            return

        if self._maybe_send_injected_error(path):
            return

        if path == "/system_stats":
            self._send_json(HTTPStatus.OK, fake.system_stats())
            return

        if path == "/models":
            self._send_json(HTTPStatus.OK, fake.list_model_folders())
            return

        if path.startswith("/models/"):
            folder = path.removeprefix("/models/").strip("/")
            self._send_json(HTTPStatus.OK, fake.list_models(folder))
            return

        if path == "/object_info":
            self._send_json(HTTPStatus.OK, fake.get_all_object_info())
            return

        if path.startswith("/object_info/"):
            node_name = path.removeprefix("/object_info/").strip("/")
            info = fake.get_object_info(node_name)
            if info is None:
                self._send_json(HTTPStatus.NOT_FOUND, {})
            else:
                self._send_json(HTTPStatus.OK, {node_name: info})
            return

        if path == "/queue":
            self._send_json(HTTPStatus.OK, fake.get_queue())
            return

        if path == "/history":
            self._send_json(HTTPStatus.OK, fake.get_all_history())
            return

        if path.startswith("/history/"):
            prompt_id = path.removeprefix("/history/").strip("/")
            entry = fake.get_history(prompt_id)
            self._send_json(HTTPStatus.OK, {prompt_id: entry} if entry is not None else {})
            return

        if path == "/view":
            filename = (query.get("filename") or [""])[0]
            subfolder = (query.get("subfolder") or [""])[0]
            folder_type = (query.get("type") or ["output"])[0]
            status, ctype, data = fake.view_artifact(filename, subfolder=subfolder, folder_type=folder_type)
            self._send_bytes(status, ctype, data)
            return

        self._send_json(HTTPStatus.NOT_FOUND, {"error": f"not found: {path}"})

    def do_POST(self) -> None:
        parsed = urlparse(self.path)
        path = parsed.path
        fake = self.server.fake

        if self._maybe_send_injected_error(path):
            return

        if path == "/upload/image":
            ctype = self.headers.get("Content-Type", "")
            try:
                raw = self._read_body()
            except ValueError as exc:
                self._send_json(HTTPStatus.BAD_REQUEST, {"error": f"invalid request body: {exc}"})
                return
            status, result = fake.handle_upload(ctype, raw)
            self._send_json(status, result)
            return

        try:
            body = self._read_json()
        except ValueError as exc:
            self._send_json(HTTPStatus.BAD_REQUEST, {"error": f"invalid json: {exc}"})
            return

        if path == "/prompt":
            status, result = fake.handle_prompt(body)
            self._send_json(status, result)
            return

        if path == "/free":
            status, result = fake.handle_free(body)
            self._send_json(status, result)
            return

        if path == "/queue":
            fake.record_queue(body)
            self._send_json(HTTPStatus.OK, {})
            return

        if path == "/interrupt":
            fake.record_interrupt(body)
            self._send_json(HTTPStatus.OK, {})
            return

        self._send_json(HTTPStatus.NOT_FOUND, {"error": f"not found: {path}"})

    def _handle_websocket(self, query: dict[str, list[str]]) -> None:
        sec_key = self.headers.get("Sec-WebSocket-Key", "")
        if not sec_key:
            self._send_json(HTTPStatus.BAD_REQUEST, {"error": "missing Sec-WebSocket-Key"})
            return

        client_id = (query.get("clientId") or query.get("client_id") or [""])[0]
        accept = _ws_accept_key(sec_key)
        response = (
            "HTTP/1.1 101 Switching Protocols\r\n"
            "Upgrade: websocket\r\n"
            "Connection: Upgrade\r\n"
            f"Sec-WebSocket-Accept: {accept}\r\n"
            "\r\n"
        ).encode("ascii")
        self.connection.sendall(response)
        self.close_connection = True

        conn = _WSServerConn(client_id, self.connection)
        fake = self.server.fake
        cur_thread = threading.current_thread()
        fake.register_ws(conn, cur_thread)
        try:
            conn.send_text({"type": "status", "data": {"status": {"exec_info": {"queue_remaining": 0}}, "sid": client_id}})
            while not conn.closed:
                try:
                    opcode, payload = _read_ws_frame(self.connection)
                except (EOFError, OSError):
                    break
                if opcode == 0x9:
                    conn.send_pong(payload)
                elif opcode == 0x8:
                    conn.close()
                    break
        finally:
            fake.unregister_ws(conn, cur_thread)


